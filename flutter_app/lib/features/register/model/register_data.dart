class RegisterData {
  final String email;
  final String name;
  final String password;
  final String confirmPassword;
  final String city;
  final String gender;
  final DateTime age;

  RegisterData({
    required this.email,
    required this.name,
    required this.password,
    required this.confirmPassword,
    required this.city,
    required this.gender,
    required this.age,
  });
}
